-- Nexura Security & Financial Dispatch Database Schema
-- Run this in your Supabase SQL Editor

CREATE TABLE IF NOT EXISTS posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  slug TEXT UNIQUE NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('bank_alert', 'data_breach', 'web_security', 'settlement', 'insurance', 'saas')),
  country TEXT NOT NULL CHECK (country IN ('us', 'uk', 'ca', 'au', 'global')),
  bank_or_entity TEXT NOT NULL,
  summary TEXT NOT NULL,
  key_takeaways JSONB DEFAULT '[]'::jsonb,
  content_html TEXT NOT NULL,
  source_url TEXT UNIQUE NOT NULL,
  source_name TEXT DEFAULT 'Official Notice',
  image_url TEXT DEFAULT '/images/bank-alert.png',
  read_time TEXT DEFAULT '4 min read',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS swift_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bank_name TEXT NOT NULL,
  swift_code TEXT NOT NULL,
  routing_number TEXT,
  country TEXT NOT NULL,
  city TEXT NOT NULL,
  address TEXT NOT NULL,
  wire_fee TEXT,
  slug TEXT UNIQUE NOT NULL,
  guide_html TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_posts_country_slug ON posts (country, slug);
CREATE INDEX IF NOT EXISTS idx_posts_category ON posts (category);
CREATE INDEX IF NOT EXISTS idx_posts_created_at ON posts (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_swift_slug ON swift_codes (slug);
CREATE INDEX IF NOT EXISTS idx_swift_country ON swift_codes (country);

-- Enable Row Level Security (public read, service_role write)
ALTER TABLE posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE swift_codes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public read access for posts"
  ON posts FOR SELECT
  USING (true);

CREATE POLICY "Public read access for swift_codes"
  ON swift_codes FOR SELECT
  USING (true);

-- Grant permissions for Supabase API roles
GRANT SELECT ON TABLE posts, swift_codes TO anon, authenticated;
GRANT ALL ON TABLE posts, swift_codes TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
